/**
 * Get actual provider URL - direct provider links
 */
export function getActualProviderUrl(providerName: string): string {
  // Normalize provider name
  const normalized = providerName.toLowerCase().trim()

  // Direct match
  if (actualProviderUrls[normalized]) {
    return actualProviderUrls[normalized]
  }

  // Try without special characters
  const cleaned = normalized.replace(/[^a-z0-9\s]/g, '').replace(/\s+/g, ' ')
  if (actualProviderUrls[cleaned]) {
    return actualProviderUrls[cleaned]
  }

  // Try without spaces
  const noSpaces = normalized.replace(/\s+/g, '')
  if (actualProviderUrls[noSpaces]) {
    return actualProviderUrls[noSpaces]
  }

  // Partial match
  for (const [key, url] of Object.entries(actualProviderUrls)) {
    if (normalized.includes(key) || key.includes(normalized)) {
      return url
    }
  }

  // Generate likely URL as last resort
  const domain = providerName
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '')
    .replace(/\s+/g, '')

  return `https://www.${domain}.com/`
}
